"""Replay equivalence: original Iter glue (83ea611) vs adapter + wmtm.api.

Both implementations run in scratch Iter-shaped trees through the same
runner (frozen clock, PYTHONHASHSEED=0) over consecutive turns. Outputs
(messages, stderr), state file, pending derives file and journal appends
must be byte-identical after every step.

Data sources (this repo contains NO real memories):
- "synthetic" (always runs): tests/fixtures/synthetic/{wmtm_state.json,
  journal.metta}, invented data generated by make_fixtures.py.
- "real" (opt-in): set WMTM_REPLAY_DATA to a directory OUTSIDE this repo
  holding a copy of a bot's memory dir: <dir>/_wmtm_state.json and
  <dir>/_journal/journal.metta (or <dir>/journal.metta). Skipped if unset.

To use a full snapshot archive as the original tree set WMTM_REPLAY_ORIG_TREE.
"""
import io, json, os, shutil, subprocess, tarfile
from pathlib import Path

import pytest

from replay import driver, scenarios

FIX = Path(__file__).resolve().parent / "fixtures"
SYNTH = FIX / "synthetic"
DATASETS = ["synthetic", "real"]


@pytest.fixture(scope="module")
def orig_src(tmp_path_factory):
    env_tree = os.environ.get("WMTM_REPLAY_ORIG_TREE")
    if env_tree:
        return Path(env_tree)
    d = tmp_path_factory.mktemp("orig_src")
    shutil.copytree(FIX / "iter_83ea611", d, dirs_exist_ok=True)
    try:
        tar = subprocess.run(["git", "-C", str(driver.REPO), "archive", "v0.1.0", "wmtm"],
                             capture_output=True, check=True).stdout
    except Exception as e:
        pytest.skip(f"needs git + tag v0.1.0 for the original package: {e}")
    tarfile.open(fileobj=io.BytesIO(tar)).extractall(d)
    return d


def _real_dir():
    d = os.environ.get("WMTM_REPLAY_DATA")
    if not d:
        pytest.skip("real-data replay skipped: set WMTM_REPLAY_DATA=<dir outside the repo> "
                    "containing _wmtm_state.json and _journal/journal.metta (see README)")
    d = Path(d).resolve()
    if d == driver.REPO or driver.REPO in d.parents:
        pytest.fail("WMTM_REPLAY_DATA must be outside the repository (real memories must never be committed)")
    return d


def _inputs(dataset):
    if dataset == "synthetic":
        st, jr = SYNTH / "wmtm_state.json", SYNTH / "journal.metta"
    else:
        d = _real_dir()
        st = d / "_wmtm_state.json"
        jr = d / "_journal" / "journal.metta"
        if not jr.exists():
            jr = d / "journal.metta"
        for p in (st, jr):
            if not p.exists():
                pytest.fail(f"WMTM_REPLAY_DATA: missing {p}")
    return st.read_text(encoding="utf-8"), jr.read_text(encoding="utf-8")


def _replay(tmp_path, orig_src, steps, state, journal, mode):
    prev = os.environ.get("WMTM_REASONER")
    os.environ["WMTM_REASONER"] = "off"   # Track L: see orig-tree note below (restored on return)
    try:
        return _replay_body(tmp_path, orig_src, steps, state, journal, mode)
    finally:
        if prev is None:
            os.environ.pop("WMTM_REASONER", None)
        else:
            os.environ["WMTM_REASONER"] = prev


def _replay_body(tmp_path, orig_src, steps, state, journal, mode):
    strict = mode == "fresh"
    res = {}
    for kind in ("orig", "new"):
        root = tmp_path / f"{kind}_{mode}"
        if kind == "orig":
            driver.build_original_tree(root, orig_src); extra = ""
            # Track L: v0.1.0 ran Python PLN by default; the new tree has no Python PLN.
            # Compare both with the reasoner off (orig: use_pln=False; new: WMTM_REASONER=off below).
            o = root / "wmtm" / "orchestrator.py"
            o.write_text(o.read_text(encoding="utf-8").replace("use_pln: bool = True", "use_pln: bool = False", 1)
                           .replace("candidates = self.engine.infer(active)", "candidates = []  # Track L: Python engine removed", 1)
                           .replace("        contradictions = self.engine.detect_contradictions(self.store)", "        return  # Track L: Python contradiction engine removed\n        contradictions = None", 1), encoding="utf-8")
        else:
            driver.build_new_tree(root); extra = str(driver.REPO)
        base = driver.seed_memory(root, state, journal)
        res[kind] = driver.run(root, steps, mode, extra, base)
        driver.structural_check(steps, res[kind], state, strict_cycle=strict)
    return res


@pytest.mark.parametrize("dataset", DATASETS)
@pytest.mark.parametrize("mode", ["fresh", "single"])
def test_live_scenario_identical(tmp_path, orig_src, mode, dataset):
    state, journal = _inputs(dataset)
    steps = scenarios.live_scenario(scenarios.clock_after(state))
    res = _replay(tmp_path, orig_src, steps, state, journal, mode)
    assert driver.diff_results(res["orig"], res["new"]) == []
    # sanity: the scenario exercised both paths and changed state
    blocks = [r["out"][-1]["content"] for s, r in zip(steps, res["new"]) if s["kind"] == "turn"]
    assert len(blocks) == sum(s["kind"] == "turn" for s in steps)
    assert res["new"][-1]["files"]["memory/_wmtm_state.json"] != state


@pytest.mark.parametrize("dataset", DATASETS)
def test_writeback_scenario_identical(tmp_path, orig_src, dataset):
    state, journal = _inputs(dataset)
    state = scenarios.writeback_state(state)
    steps = scenarios.live_scenario(scenarios.clock_after(state))[:5]
    res = _replay(tmp_path, orig_src, steps, state, journal, "fresh")
    assert driver.diff_results(res["orig"], res["new"]) == []
    tail = res["new"][-1]["files"]["journal_tail"]
    assert tail.count(";;; BEGIN MemoryCluster") >= 1, "writeback path not exercised"


def test_synthetic_fixture_exercises_engine():
    """The synthetic state must look like a live one: recalled and derived
    items, utility records and a forgetting log."""
    s = json.loads((SYNTH / "wmtm_state.json").read_text(encoding="utf-8"))
    kinds = {i["source_type"] for i in s["store"]["items"].values()}
    assert {"recalled", "derived"} <= kinds
    assert s["utility"]["records"] and s["forgetting_log"]["records"]
    j = (SYNTH / "journal.metta").read_text(encoding="utf-8")
    for atom in ("(Supersedes ", "(WMTMUtility ", "ClusterType ", "AUTOCYCLE"):
        assert atom in j


@pytest.mark.parametrize("impl", ["orig", "new"])
def test_known_answer_canary(tmp_path, orig_src, impl):
    """Gate check 1: a fact only the journal knows must reach the prompt
    through the real path, then survive an automated tick and a derive."""
    root = tmp_path / impl
    if impl == "orig":
        driver.build_original_tree(root, orig_src); extra = ""
    else:
        driver.build_new_tree(root); extra = str(driver.REPO)
    base = driver.seed_memory(root, None, scenarios.DECOY_CLUSTER + scenarios.CANARY_CLUSTER)
    steps = scenarios.canary_steps()
    r = driver.run(root, steps, "fresh", extra, base)
    driver.structural_check(steps, r, None)
    b1 = r[0]["out"][-1]["content"]
    assert "zebra-quartz-41" in b1 and "[recalled " in b1
    assert "tomato" not in b1                        # decoy not recalled
    assert b1.startswith("[WMTM Active Working Memory (1 items, showing top 1, cycle 1)]")
    st1 = json.loads(r[0]["files"]["memory/_wmtm_state.json"])
    sti1 = st1["store"]["items"]["ep-note-20261015T180000Z"]["attention"]["sti"]
    st2 = json.loads(r[2]["files"]["memory/_wmtm_state.json"])
    sti2 = st2["store"]["items"]["ep-note-20261015T180000Z"]["attention"]["sti"]
    assert abs(sti2 - sti1 * 0.9) < 1e-9             # fast path: exactly one 0.9 decay
    assert st2["cycle"] == st1["cycle"] + 1
    assert "zebra-quartz-41" in r[2]["out"][-1]["content"]
    b4 = r[3]["out"][-1]["content"]
    assert scenarios.DERIVE_CANARY in b4 and "[derived sti=" in b4
    assert r[3]["files"]["memory/_wmtm_pending_derives.jsonl"] == ""
